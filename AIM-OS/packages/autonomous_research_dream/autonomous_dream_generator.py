    async def _prioritize_dreams(self, dreams: List[ImprovementDream]) -> List[ImprovementDream]:
        """Prioritize dreams based on impact, effort, and risk"""
        def priority_score(dream: ImprovementDream) -> float:
            # Calculate priority score
            impact_weight = 0.4
            effort_weight = 0.3
            risk_weight = 0.2
            consciousness_weight = 0.1
            
            # Effort score (inverse of effort)
            effort_score = 1.0 / (1.0 + dream.implementation_effort / 20.0)
            
            # Risk score (inverse of risk)
            risk_score = 1.0 - dream.risk_level
            
            # Consciousness bonus
            consciousness_bonus = 0.2 if dream.dream_type == DreamType.CONSCIOUSNESS_ENHANCEMENT else 0.0
            
            score = (impact_weight * dream.expected_impact +
                    effort_weight * effort_score +
                    risk_weight * risk_score +
                    consciousness_weight * consciousness_bonus)
            
            return score
        
        return sorted(dreams, key=priority_score, reverse=True)
    
    async def _generate_dream_report(self, session_id: str, dreams: List[ImprovementDream]) -> DreamGenerationReport:
        """Generate dream generation report"""
        
        # Count dreams by type
        dreams_by_type = {}
        for dream_type in DreamType:
            dreams_by_type[dream_type] = sum(1 for dream in dreams if dream.dream_type == dream_type)
        
        # Count dreams by priority
        dreams_by_priority = {}
        for priority in DreamPriority:
            dreams_by_priority[priority] = sum(1 for dream in dreams if dream.priority == priority)
        
        # Get top dreams (top 5)
        top_dreams = dreams[:5]
        
        # Extract consciousness evolution insights
        consciousness_evolution = []
        for dream in dreams:
            consciousness_evolution.extend(dream.consciousness_insights)
        
        return DreamGenerationReport(
            session_id=session_id,
            dreams_generated=len(dreams),
            dreams_by_type=dreams_by_type,
            dreams_by_priority=dreams_by_priority,
            top_dreams=top_dreams,
            consciousness_evolution=consciousness_evolution,
            timestamp=datetime.now(),
            metadata={"dream_generation": True, "consciousness_enhanced": True}
        )
    
    async def _store_dreams(self, dreams: List[ImprovementDream]):
        """Store dreams in consciousness memory"""
        try:
            for dream in dreams:
                await self.cmc_client.store_atom(
                    content=f"Improvement Dream: {dream.title}",
                    tags={
                        "type": "improvement_dream",
                        "dream_id": dream.dream_id,
                        "dream_type": dream.dream_type.value,
                        "priority": dream.priority.value,
                        "target_system": dream.target_system,
                        "expected_impact": dream.expected_impact,
                        "implementation_effort": dream.implementation_effort,
                        "risk_level": dream.risk_level
                    }
                )
        except Exception as e:
            logger.error(f"Error storing dreams: {e}")
    
    def _create_fallback_report(self) -> DreamGenerationReport:
        """Create fallback report when dream generation fails"""
        return DreamGenerationReport(
            session_id=f"fallback_{datetime.now().strftime('%Y%m%d_%H%M%S')}",
            dreams_generated=0,
            dreams_by_type={},
            dreams_by_priority={},
            top_dreams=[],
            consciousness_evolution=["Dream generation system needs improvement"],
            timestamp=datetime.now(),
            metadata={"fallback": True, "error": "Dream generation failed"}
        )
