// Helper to get templates by category
export const getTemplatesByCategory = (category: TemplateCategory | 'all'): Template[] => {
  if (category === 'all') return TEMPLATES
  return TEMPLATES.filter(t => t.type === category)
}

// Helper to get category config
export const getCategoryConfig = (categoryId: TemplateCategory): CategoryConfig | undefined => {
  return CATEGORIES.find(c => c.id === categoryId)
}

// Helper to search templates
export const searchTemplates = (query: string, category?: TemplateCategory): Template[] => {
  const lowerQuery = query.toLowerCase()
  return TEMPLATES.filter(t => {
    const matchesCategory = !category || t.type === category
    const matchesSearch = 
      t.name.toLowerCase().includes(lowerQuery) ||
      t.description.toLowerCase().includes(lowerQuery) ||
      t.tags.some(tag => tag.toLowerCase().includes(lowerQuery))
    return matchesCategory && matchesSearch
  })
}

