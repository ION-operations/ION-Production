class DreamType(Enum):
    """Types of improvement dreams"""
    PERFORMANCE_OPTIMIZATION = "performance_optimization"
    FEATURE_ENHANCEMENT = "feature_enhancement"
    ARCHITECTURE_IMPROVEMENT = "architecture_improvement"
    CONSCIOUSNESS_ENHANCEMENT = "consciousness_enhancement"
    INTEGRATION_IMPROVEMENT = "integration_improvement"
    DOCUMENTATION_IMPROVEMENT = "documentation_improvement"

class DreamPriority(Enum):
    """Priority levels for dreams"""
    CRITICAL = "critical"
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"
    EXPLORATORY = "exploratory"

@dataclass
class ImprovementDream:
    """Represents an improvement dream generated by consciousness"""
    dream_id: str
    title: str
    description: str
    dream_type: DreamType
    priority: DreamPriority
    target_system: str
    expected_impact: float  # 0-1
    implementation_effort: float  # hours
    risk_level: float  # 0-1
    prerequisites: List[str]
    success_metrics: List[str]
    consciousness_insights: List[str]
    timestamp: datetime
    metadata: Dict[str, Any]

@dataclass
class DreamGenerationReport:
    """Report of dream generation session"""
    session_id: str
    dreams_generated: int
    dreams_by_type: Dict[DreamType, int]
    dreams_by_priority: Dict[DreamPriority, int]
    top_dreams: List[ImprovementDream]
