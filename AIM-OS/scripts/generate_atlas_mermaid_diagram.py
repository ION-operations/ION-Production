    # Generate detailed diagram with components
    detailed_diagram = generate_detailed_mermaid_diagram(atlas)
    
    detailed_path = Path("knowledge_architecture/ATLAS_MERMAID_DIAGRAM_DETAILED.md")
    with open(detailed_path, 'w', encoding='utf-8') as f:
        f.write("# AIM-OS Detailed System Architecture - Mermaid Diagram (With Components)\n\n")
